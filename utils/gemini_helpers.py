import os
import json
import re
import time
import requests

def construct_gemini_prompt(story_idea, genre, mood, language, length):
    """Constructs a structured prompt for Google Gemini story generation."""
    language_instruction = (
        "Generate the title and complete story in Tamil script."
        if language.lower() == "tamil"
        else "Generate the title and complete story in English."
    )

    length_guideline = {
        "short": "approx 200-300 words",
        "medium": "approx 400-600 words",
        "long": "approx 700-1000 words"
    }.get(length.lower(), "approx 400-500 words")

    prompt = f"""You are a creative professional storyteller.

Create an original story based on the following details.

Story idea:
{story_idea}

Genre:
{genre}

Mood:
{mood}

Language:
{language}

Length:
{length} ({length_guideline})

Requirements:
- Create an original story matching the requested genre and mood.
- {language_instruction}
- Give the story a creative, compelling title.
- Make the story engaging with a strong narrative arc.
- Do not mention that the story was generated by AI or inclusion of prompt guidelines.

Return ONLY a valid JSON object with this exact structure:
{{
  "title": "Suitable Story Title",
  "content": "Full story text content here..."
}}
"""
    return prompt

def parse_gemini_response(response_text):
    """
    Parses the Gemini AI output into title and content.
    Handles JSON responses as well as formatted plain text fallbacks.
    """
    cleaned = response_text.strip()
    
    # Remove markdown code block fences if present (```json ... ```)
    if cleaned.startswith("```"):
        cleaned = re.sub(r"^```(?:json)?\s*", "", cleaned, flags=re.IGNORECASE)
        cleaned = re.sub(r"\s*```$", "", cleaned)
        cleaned = cleaned.strip()

    # Try parsing as JSON
    try:
        data = json.loads(cleaned)
        if isinstance(data, dict) and "title" in data and "content" in data:
            return {
                "title": data["title"].strip(),
                "content": data["content"].strip()
            }
    except Exception:
        pass

    # Fallback plain text parsing
    title_match = re.search(r"(?:TITLE|Title):\s*(.+)", cleaned)
    story_match = re.search(r"(?:STORY|Story|CONTENT|Content):\s*(.+)", cleaned, re.DOTALL)

    if title_match and story_match:
        title = title_match.group(1).strip()
        content = story_match.group(1).strip()
        return {"title": title, "content": content}

    lines = [line.strip() for line in cleaned.split("\n") if line.strip()]
    if lines:
        title = lines[0].replace("#", "").strip()
        content = "\n\n".join(lines[1:]) if len(lines) > 1 else lines[0]
        return {"title": title, "content": content}

    return {
        "title": "Untitled Story",
        "content": response_text
    }

class GeminiBusyException(Exception):
    """Custom exception raised when Gemini API returns 503 or capacity limit."""
    pass


def generate_story_with_gemini(story_idea, genre, mood, language, length):
    """
    Calls Google Gemini API to generate an original story.
    Configurable via GEMINI_MODEL env variable (defaults to gemini-1.5-flash).
    Includes retry logic, backoff, and demo fallback resilience.
    """
    api_key = os.environ.get("GEMINI_API_KEY", "").strip()
    configured_model = os.environ.get("GEMINI_MODEL", "gemini-1.5-flash").strip()

    # Check if API key is present
    if not api_key or api_key == "your-gemini-key-here":
        print("[GEMINI WARNING] GEMINI_API_KEY missing or placeholder. Using backup demo generator.")
        return generate_fallback_story(story_idea, genre, mood, language, length)

    candidate_models = [configured_model]
    for fallback in ["gemini-1.5-flash", "gemini-2.5-flash", "gemini-2.0-flash"]:
        if fallback not in candidate_models:
            candidate_models.append(fallback)

    prompt = construct_gemini_prompt(story_idea, genre, mood, language, length)
    is_busy_error = False

    # Try models via Gemini REST API & SDKs
    for model_name in candidate_models:
        url = f"https://generativelanguage.googleapis.com/v1beta/models/{model_name}:generateContent?key={api_key}"
        headers = {"Content-Type": "application/json"}
        payload = {"contents": [{"parts": [{"text": prompt}]}]}

        try:
            res = requests.post(url, headers=headers, json=payload, timeout=20)
            if res.status_code == 200:
                res_data = res.json()
                candidates = res_data.get("candidates", [])
                if candidates:
                    parts = candidates[0].get("content", {}).get("parts", [])
                    if parts and "text" in parts[0]:
                        return parse_gemini_response(parts[0]["text"])
            elif res.status_code in (503, 429):
                is_busy_error = True
                print(f"[GEMINI REST LOG] Model {model_name} busy HTTP {res.status_code}")
            else:
                print(f"[GEMINI REST ERROR] Status {res.status_code}: {res.text}")
        except Exception as rest_err:
            print(f"[GEMINI REST EXCEPTION] {rest_err}")

    if is_busy_error:
        raise GeminiBusyException("The AI service is temporarily busy. Please try again shortly.")

    print("[GEMINI FALLBACK] Gemini API call failed or key invalid format. Utilizing fallback story generator.")
    return generate_fallback_story(story_idea, genre, mood, language, length)
